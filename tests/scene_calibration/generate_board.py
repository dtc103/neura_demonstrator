"""Create a metric ChArUco board as printable SVG plus its detection definition."""

import argparse
import json
from pathlib import Path

import cv2
import numpy as np


def make_board(definition):
    dictionary = cv2.aruco.getPredefinedDictionary(getattr(cv2.aruco, definition["dictionary"]))
    board = cv2.aruco.CharucoBoard(
        (definition["squares_x"], definition["squares_y"]),
        definition["square_length_m"], definition["marker_length_m"], dictionary)
    board.setLegacyPattern(definition.get("legacy_pattern", False))
    return board


def definition(square_mm=25.0):
    return {"dictionary": "DICT_6X6_250", "squares_x": 5, "squares_y": 7,
            "square_length_m": square_mm / 1000, "marker_length_m": square_mm * 0.7 / 1000,
            "legacy_pattern": False}


def svg_board(config):
    board = make_board(config)
    # Integer square and marker widths keep the generated marker cells crisp.
    image = board.generateImage((config["squares_x"] * 320, config["squares_y"] * 320), marginSize=0)
    square_mm = config["square_length_m"] * 1000
    width_mm = config["squares_x"] * square_mm
    height_mm = config["squares_y"] * square_mm
    if width_mm > 180 or height_mm > 250:
        raise ValueError("Board is too large for this A4 layout; use a smaller square size")
    left, top = (210 - width_mm) / 2, (297 - height_mm) / 2
    # Collapse identical adjacent rows into vector rectangles instead of embedding
    # a raster image. The pattern is exactly the one generated by OpenCV.
    rectangles = []
    start = 0
    for end in range(1, image.shape[0] + 1):
        if end < image.shape[0] and np.array_equal(image[start], image[end]):
            continue
        black = np.pad(image[start] == 0, (1, 1)).astype(np.int8)
        changes = np.diff(black)
        for x1, x2 in zip(np.flatnonzero(changes == 1), np.flatnonzero(changes == -1)):
            rectangles.append(f'<rect x="{x1}" y="{start}" width="{x2-x1}" height="{end-start}"/>')
        start = end
    return f'''<svg xmlns="http://www.w3.org/2000/svg" width="210mm" height="297mm" viewBox="0 0 210 297">
<rect width="210" height="297" fill="white"/>
<text x="105" y="18" text-anchor="middle" font-family="sans-serif" font-size="4">ChArUco 5 x 7 · DICT_6X6_250</text>
<text x="105" y="25" text-anchor="middle" font-family="sans-serif" font-size="3.5">Squares {square_mm:g} mm · Pattern {width_mm:g} x {height_mm:g} mm</text>
<svg x="{left}" y="{top}" width="{width_mm}" height="{height_mm}" viewBox="0 0 {image.shape[1]} {image.shape[0]}">
<g fill="black">{''.join(rectangles)}</g>
</svg>
<text x="105" y="279" text-anchor="middle" font-family="sans-serif" font-size="3.5">Print A4 portrait at 100% / actual size. Disable fit-to-page.</text>
<text x="105" y="286" text-anchor="middle" font-family="sans-serif" font-size="3.5">Verify square pitch horizontally and vertically after printing.</text>
</svg>
'''


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--square-mm", type=float, default=25)
    parser.add_argument("--output", type=Path, default=Path(__file__).parent / "board")
    args = parser.parse_args()
    if not np.isfinite(args.square_mm) or args.square_mm <= 0:
        parser.error("--square-mm must be a positive finite length")
    config = definition(args.square_mm)
    svg = svg_board(config)
    args.output.mkdir(parents=True, exist_ok=True)
    (args.output / "charuco_a4.svg").write_text(svg)
    (args.output / "board.json").write_text(json.dumps(config, indent=2) + "\n")
    print(f"Print: {args.output / 'charuco_a4.svg'}")
    print(f"Definition: {args.output / 'board.json'}")


if __name__ == "__main__":
    main()
